function runSelfChecks() {
  results.length = 0;

  check("skill directory is named " + SKILL_NAME, () => {
    assert(isDirectory(SKILL_DIR), "skill directory not found: " + SKILL_DIR);
    assert(SKILL_DIR.split(sep).pop() === SKILL_NAME, "directory name must equal the frontmatter name: " + SKILL_NAME);
    return { detail: SKILL_DIR };
  });

  const skillMd = join(SKILL_DIR, "SKILL.md");
  let document = null;

  check("SKILL.md exists and is not a stub", () => {
    const size = fileSize(skillMd);
    assert(size > 2000, "SKILL.md is too small: " + size + " bytes");
    document = readText(skillMd);
    return { detail: size + " bytes" };
  });

  check("SKILL.md frontmatter parses and matches the directory name", () => {
    const parsed = parseFrontmatter(document, "SKILL.md");
    assert(parsed.meta.name === SKILL_NAME, "frontmatter name must be '" + SKILL_NAME + "', got: " + parsed.meta.name);
    assert(typeof parsed.meta.description === "string", "frontmatter description is missing");
    const length = parsed.meta.description.trim().length;
    assert(length >= 80, "frontmatter description is too short to explain when to use the skill: " + length);
    assert(length <= 1024, "frontmatter description is too long: " + length);
    assert(!CJK.test(document), "SKILL.md must be English-only (CJK characters found)");
    return { detail: "name=" + parsed.meta.name + ", description=" + length + " chars" };
  });

  check("SKILL.md documents the required sections", () => {
    const lower = document.toLowerCase();
    const required = [
      "when to use",
      "when not to use",
      "input contract",
      "workflow",
      "quality gates",
      "value",
      "boundaries",
      "examples",
      "anti-pattern",
    ];
    const missing = required.filter((section) => lower.indexOf(section) === -1);
    assert(missing.length === 0, "missing sections: " + missing.join(", "));
    return { detail: required.length + " sections" };
  });

  check("SKILL.md names the bundled scripts and command examples", () => {
    const required = ["scaffold.mjs", "check-project.mjs", "--self", "--skeleton", "Node.js 20", "BYOK", "GitHub Pages"];
    const missing = required.filter((token) => document.indexOf(token) === -1);
    assert(missing.length === 0, "missing content tokens: " + missing.join(", "));
    return { detail: required.length + " tokens" };
  });

  check("required skill files exist", () => {
    const missing = SKILL_REQUIRED_FILES.filter((file) => !existsSync(join(SKILL_DIR, file)));
    assert(missing.length === 0, "missing files: " + missing.join(", "));
    return { detail: SKILL_REQUIRED_FILES.length + " files" };
  });

  check("reference templates use only known placeholders", () => {
    const unknown = new Set();
    for (const name of REFERENCE_FILES) {
      const file = join(SKILL_DIR, "references", name);
      const text = readText(file);
      assert(!CJK.test(text), "references/" + name + " must be English-only (CJK characters found)");
      const found = placeholdersIn(text);
      assert(found.length > 0, "references/" + name + " should contain placeholders for the scaffold");
      for (const key of found) {
        if (KNOWN_PLACEHOLDERS.indexOf(key) === -1) unknown.add(key);
      }
    }
    assert(unknown.size === 0, "unknown placeholders: " + Array.from(unknown).join(", "));
    return { detail: KNOWN_PLACEHOLDERS.length + " supported placeholders" };
  });

  check("design tokens reference contains an extractable css block", () => {
    const text = readText(join(SKILL_DIR, "references", "design-tokens.md"));
    assert(/```css\r?\n[\s\S]*?```/.test(text), "references/design-tokens.md needs a fenced css block for the scaffold");
    return { detail: "css token block found" };
  });

  check("scripts are English-only and self-documenting", () => {
    for (const name of ["scaffold.mjs", "check-project.mjs"]) {
      const text = readText(join(SCRIPT_DIR, name));
      assert(!CJK.test(text), "scripts/" + name + " must be English-only (CJK characters found)");
      assert(text.indexOf("/**") !== -1, "scripts/" + name + " needs a JSDoc header");
    }
    return { detail: "2 scripts" };
  });

  check("scaffold.mjs is executable and prints usage", () => {
    const result = runNode([join(SCRIPT_DIR, "scaffold.mjs"), "--help"]);
    if (result.skipped) return { skip: true, detail: result.reason };
    assert(result.ok, "scaffold.mjs --help failed (exit " + result.status + "): " + result.stderr.slice(0, 300));
    assert(result.stdout.indexOf("Usage") !== -1, "scaffold.mjs --help does not print a usage block");
    return { detail: "exit 0" };
  });

  check("check-project.mjs is executable and prints usage", () => {
    const result = runNode([join(SCRIPT_DIR, "check-project.mjs"), "--help"]);
    if (result.skipped) return { skip: true, detail: result.reason };
    assert(result.ok, "check-project.mjs --help failed (exit " + result.status + "): " + result.stderr.slice(0, 300));
    assert(result.stdout.indexOf("Usage") !== -1, "check-project.mjs --help does not print a usage block");
    return { detail: "exit 0" };
  });

  check("examples/prompts.md covers five domains with deliverables", () => {
    const text = readText(join(SKILL_DIR, "examples", "prompts.md"));
    const deliverables = text.split("Expected deliverables").length - 1;
    assert(deliverables >= 5, "expected at least 5 prompt examples with expected deliverables, found: " + deliverables);
    const domains = ["llm", "open source", "paper", "policy", "competitor"];
    const missing = domains.filter((domain) => text.toLowerCase().indexOf(domain) === -1);
    assert(missing.length === 0, "missing example domains: " + missing.join(", "));
    return { detail: deliverables + " prompt examples" };
  });

  const skillReadme = join(SKILLS_DIR, "README.md");
  // A standalone install (e.g. copied into ~/.dsh/skills/one-sentence-project)
  // has no repository-level skills/README.md; the index checks apply only in-repo.
  const repoReadmeSkip = existsSync(skillReadme)
    ? null
    : { skip: true, detail: "standalone install: repository-level skills/README.md is not part of the package" };

  check("skills/README.md documents the skill index and usage", () => {
    if (repoReadmeSkip) return repoReadmeSkip;
    const text = readText(skillReadme);
    assert(text.length > 1500, "skills/README.md is too short: " + text.length + " chars");
    const required = ["## Index", "## Install", "## Usage", "## Maintenance", "## Mapping", "one-sentence-project"];
    const missing = required.filter((token) => text.indexOf(token) === -1);
    assert(missing.length === 0, "missing sections: " + missing.join(", "));
    return { detail: text.length + " chars" };
  });

  check("skills/README.md value and boundaries summary is present", () => {
    if (repoReadmeSkip) return repoReadmeSkip;
    const text = readText(skillReadme);
    const lower = text.toLowerCase();
    assert(lower.indexOf("value") !== -1 && lower.indexOf("boundar") !== -1, "README must state value and boundaries");
    const lines = text.split(/\r?\n/);
    const start = lines.findIndex((line) => line.toLowerCase().indexOf("value") !== -1 && line.indexOf("#") === 0);
    assert(start >= 0, "README needs a value/boundaries heading near the top");
    assert(start <= 6, "value/boundaries summary should be at the top of skills/README.md, found at line " + (start + 1));
    return { detail: "summary at line " + (start + 1) };
  });

  check("skills/README.md relative links resolve", () => {
    if (repoReadmeSkip) return repoReadmeSkip;
    const text = readText(skillReadme);
    const broken = [];
    for (const link of markdownLinks(text)) {
      if (/^(https?:|mailto:|#)/.test(link)) continue;
      const clean = link.split("#")[0];
      if (!clean || clean.indexOf("/") === 0) continue;
      const target = resolve(SKILLS_DIR, clean);
      if (!existsSync(target)) broken.push(link);
    }
    assert(broken.length === 0, "broken relative links: " + broken.join(", "));
    return { detail: markdownLinks(text).length + " links checked" };
  });

  check("repository mapping points at existing files", () => {
    const inRepo = existsSync(join(REPO_ROOT, "docs", "SPEC.md"));
    if (!inRepo) {
      return { skip: true, detail: "standalone package: source repository not found next to skills/" };
    }
    const mapping = [
      "docs/SPEC.md",
      "docs/DATA-CONTRACT.md",
      "docs/ACCEPTANCE.md",
      "docs/POC-REPORT.md",
      "docs/V1.1-CONTRACT.md",
      "docs/AI-SHARE.md",
      "scripts/serve.mjs",
      "scripts/validate.mjs",
      "site/index.html",
      ".github/workflows/ci.yml",
      ".github/workflows/deploy.yml",
      "README.md",
    ];
    const missing = mapping.filter((file) => !existsSync(join(REPO_ROOT, file)));
    assert(missing.length === 0, "source repository is missing: " + missing.join(", "));
    const readme = readText(skillReadme);
    const broken = mapping.filter((file) => readme.indexOf(file) === -1);
    assert(broken.length === 0, "skills/README.md mapping table does not mention: " + broken.join(", "));
    return { detail: mapping.length + " mapped files" };
  });

  return report("SELF: skill package");
}

