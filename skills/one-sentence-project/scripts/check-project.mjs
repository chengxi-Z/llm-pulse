class CheckError extends Error {}

function assert(condition, message) {
  if (!condition) throw new CheckError(message);
}

function readText(file) {
  assert(existsSync(file), "missing file: " + file);
  return readFileSync(file, "utf8");
}

function isDirectory(path) {
  return existsSync(path) && statSync(path).isDirectory();
}

function fileSize(path) {
  return existsSync(path) ? statSync(path).size : -1;
}

function runNode(args, options) {
  const result = { ok: false, skipped: false, status: null, stdout: "", stderr: "" };
  try {
    result.stdout = execFileSync(process.execPath, args, Object.assign(
      { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], timeout: 30000 },
      options || {}
    ));
    result.ok = true;
    result.status = 0;
    return result;
  } catch (error) {
    if (error && (error.code === "EPERM" || error.code === "EACCES")) {
      result.skipped = true;
      result.reason = "child processes are not available in this environment (" + error.code + ")";
      return result;
    }
    result.status = error && typeof error.status === "number" ? error.status : -1;
    result.stdout = error && error.stdout ? String(error.stdout) : "";
    result.stderr = error && error.stderr ? String(error.stderr) : String(error && error.message ? error.message : error);
    return result;
  }
}

function parseFrontmatter(text, label) {
  const normalized = text.replace(/^\uFEFF/, "");
  assert(normalized.indexOf("---") === 0, label + " must start with YAML frontmatter (---)");
  const end = normalized.indexOf("\n---", 3);
  assert(end > 0, label + " frontmatter is not closed with ---");
  const block = normalized.slice(3, end);
  const meta = {};
  for (const rawLine of block.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.indexOf("#") === 0) continue;
    const colon = line.indexOf(":");
    assert(colon > 0, label + " has an invalid frontmatter line: " + line);
    const key = line.slice(0, colon).trim();
    let value = line.slice(colon + 1).trim();
    if (value.length >= 2) {
      const first = value.charAt(0);
      const last = value.charAt(value.length - 1);
      if ((first === "\"" && last === "\"") || (first === "'" && last === "'")) {
        value = value.slice(1, -1);
      }
    }
    meta[key] = value;
  }
  return { meta, body: normalized.slice(end + 4) };
}

function markdownLinks(text) {
  const links = [];
  const pattern = /\[[^\]]*\]\(([^)\s]+)\)/g;
  let match = pattern.exec(text);
  while (match !== null) {
    links.push(match[1]);
    match = pattern.exec(text);
  }
  return links;
}

function walkFiles(root, prefix, output) {
  const entries = readdirSync(join(root, prefix), { withFileTypes: true });
  for (const entry of entries) {
    const relativePath = prefix ? prefix + "/" + entry.name : entry.name;
    if (entry.isDirectory()) {
      const normalized = relativePath.split(sep).join("/");
      if (SKELETON_SKIP_DIRS.has(normalized)) continue;
      if (SKELETON_SKIP_DIRS.has(entry.name)) continue;
      walkFiles(root, relativePath, output);
    } else if (entry.isFile()) {
      output.push(relativePath);
    }
  }
}

function placeholdersIn(text) {
  const found = [];
  PLACEHOLDER.lastIndex = 0;
  let match = PLACEHOLDER.exec(text);
  while (match !== null) {
    found.push(match[1]);
    match = PLACEHOLDER.exec(text);
  }
  return found;
}

