/* ------------------------------------------------------------------------- */

function main() {
  const argv = process.argv.slice(2);
  let self = false;
  let skeletonDir = null;
  let help = false;
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--help" || arg === "-h") help = true;
    else if (arg === "--self") self = true;
    else if (arg === "--skeleton") {
      const value = argv[index + 1];
      if (!value || value.indexOf("--") === 0) {
        console.error("[" + SKILL_NAME + "] --skeleton requires a directory\n\n" + USAGE);
        process.exit(2);
      }
      skeletonDir = value;
      index += 1;
    } else {
      console.error("[" + SKILL_NAME + "] unknown argument: " + arg + "\n\n" + USAGE);
      process.exit(2);
    }
  }
  if (help) {
    console.log(USAGE);
    process.exit(0);
  }
  if (!self && !skeletonDir) {
    console.error("[" + SKILL_NAME + "] choose --self and/or --skeleton <dir>\n\n" + USAGE);
    process.exit(2);
  }

  let failures = 0;
  if (self) failures += runSelfChecks();
  if (skeletonDir) {
    if (!isDirectory(resolve(process.cwd(), skeletonDir))) {
      console.error("[" + SKILL_NAME + "] skeleton directory not found: " + resolve(process.cwd(), skeletonDir));
      process.exit(2);
    }
    failures += runSkeletonChecks(skeletonDir);
  }

  console.log("");
  if (failures > 0) {
    console.log("[" + SKILL_NAME + "] FAILED: " + failures + " check(s) failed.");
    process.exit(1);
  }
  console.log("[" + SKILL_NAME + "] OK: all checks passed.");
  process.exit(0);
}

main();
