const results = [];

function check(name, fn) {
  try {
    const value = fn();
    if (value && value.skip) {
      results.push({ name, status: "SKIP", detail: value.detail || "" });
    } else {
      results.push({ name, status: "PASS", detail: value && value.detail ? value.detail : "" });
    }
  } catch (error) {
    results.push({
      name,
      status: "FAIL",
      detail: error && error.message ? error.message : String(error),
    });
  }
}

function report(group) {
  console.log("");
  console.log("[" + SKILL_NAME + "] " + group);
  for (const result of results) {
    const detail = result.detail ? "  (" + result.detail + ")" : "";
    console.log("  " + result.status.padEnd(4) + "  " + result.name + detail);
  }
  const passed = results.filter((result) => result.status === "PASS").length;
  const failed = results.filter((result) => result.status === "FAIL").length;
  const skipped = results.filter((result) => result.status === "SKIP").length;
  console.log("");
  console.log("Result: " + passed + " passed, " + failed + " failed, " + skipped + " skipped");
  return failed;
}

